import Foundation

@testable import KiwiDeskCore

/// The in-repo test desk (#3121): the config a `KIWIDESK_HOME`
/// instance starts from, stated as values and written through the
/// real stores, so the checked-in files are what this build would
/// write. `TestDeskFixtureTests` holds the files to it, and
/// `scripts/test-desk regen` rewrites them.
///
/// Six Spaces, one layout each, so one desk reaches every layout.
/// No profile names a real screen: each is its screen count's
/// default, matched on any host with that many screens.
enum TestDeskFixture {
    /// `Tests/KiwiDeskCoreTests/TestDesk/config`, excluded from the
    /// target in `Package.swift` and read by path.
    static let configDirectory = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .appendingPathComponent("TestDesk/config")

    static let spaces: [SpaceID] = (1...6).map { SpaceID("\($0)") }

    static let modes: [SpaceID: LayoutMode] = [
        SpaceID("2"): .scrolling,
        SpaceID("3"): .stack,
        SpaceID("4"): .monocle,
        SpaceID("5"): .grid,
        SpaceID("6"): .floating,
    ]

    /// A fixed stamp, so a regeneration changes no byte it need not.
    static let savedAt = Date(timeIntervalSince1970: 1_793_750_400)

    static func guiConfig() -> GuiConfig {
        var config = GuiConfig()
        config.spaces = spaces
        config.spaceModes = modes
        if let index = config.layers.firstIndex(where: \.isDefault) {
            config.layers[index].bindings = DefaultKeybindings.bindings(
                spaces: spaces,
                resizeStep: Int(config.settings.resizeStep),
                base: config.shortcutBase
            )
        }
        return config
    }

    static func profiles() -> [Profile] {
        [
            profile("Test", id: "test-desk-1", screens: ["Fixture A"]),
            profile(
                "Test Dual",
                id: "test-desk-2",
                screens: ["Fixture A", "Fixture B"]
            ),
        ]
    }

    private static func profile(
        _ name: String,
        id: String,
        screens: [String]
    ) -> Profile {
        Profile(
            id: ProfileID(raw: id),
            name: name,
            monitorSets: [
                MonitorSet(monitors: screens.map { "\($0):2560x1440" })
            ],
            isDefault: true,
            spaces: spaces,
            spaceModes: modes,
            settings: TilingSettings(),
            savedAt: savedAt
        )
    }

    /// Writes the desk into `config`; `machine` takes the files
    /// the stores split off for this Mac, which the desk omits.
    /// Main actor for `ProfileManager`: a few small file writes.
    @MainActor
    static func write(config: URL, machine: URL) throws {
        try GuiConfigStore(directory: config, machine: machine)
            .save(guiConfig())
        let manager = ProfileManager(
            directory: config.appendingPathComponent("profiles")
        )
        for profile in profiles() {
            try manager.write(profile)
        }
        try initLua.write(
            to: config.appendingPathComponent("init.lua"),
            atomically: true,
            encoding: .utf8
        )
    }

    /// Declares no managed setting, so `gui.json` owns the desk.
    static let initLua = """
        -- KiwiDesk test desk (#3121). Generated by
        -- scripts/test-desk regen; never edit it by hand.
        -- gui.json and profiles/ own the settings, so this file
        -- declares none. A check that needs Lua appends to the
        -- copy `scripts/test-desk up` makes, never to this file.

        """
}
